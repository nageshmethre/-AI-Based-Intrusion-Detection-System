import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  AlertOctagon,
  Filter,
  RefreshCw,
  Search,
  ArrowRight,
  ShieldAlert,
  CheckCircle2,
  Clock,
  ChevronLeft,
  ChevronRight
} from 'lucide-react';
import { api } from '../services/api';

export function AlertsPage() {
  const navigate = useNavigate();
  const [alerts, setAlerts] = useState([]);
  const [total, setTotal] = useState(0);
  const [page, setPage] = useState(1);
  const [loading, setLoading] = useState(true);
  const [statusTab, setStatusTab] = useState('ALL');
  const [severityFilter, setSeverityFilter] = useState('');
  const [sourceIp, setSourceIp] = useState('');

  const fetchAlerts = async () => {
    try {
      setLoading(true);
      const params = { page, page_size: 25 };
      if (statusTab !== 'ALL') params.status = statusTab;
      if (severityFilter) params.severity = severityFilter;
      if (sourceIp) params.source_ip = sourceIp;

      const res = await api.getAlerts(params);
      setAlerts(res.items || []);
      setTotal(res.total || 0);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, [page, statusTab, severityFilter]);

  const severityBadges = {
    CRITICAL: 'bg-rose-500/20 text-rose-300 border-rose-500/40',
    HIGH: 'bg-orange-500/20 text-orange-300 border-orange-500/40',
    MEDIUM: 'bg-amber-500/20 text-amber-300 border-amber-500/40',
    LOW: 'bg-yellow-500/15 text-yellow-300 border-yellow-500/30'
  };

  const statusBadges = {
    NEW: 'bg-rose-950/60 text-rose-400 border-rose-800',
    INVESTIGATING: 'bg-amber-950/60 text-amber-400 border-amber-800',
    RESOLVED: 'bg-emerald-950/60 text-emerald-400 border-emerald-800',
    FALSE_POSITIVE: 'bg-neutral-900 text-neutral-400 border-neutral-700'
  };

  return (
    <div className="space-y-4">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="text-xl font-bold tracking-tight text-white flex items-center gap-2">
            <span>Security Alerts Center</span>
            <span className="text-xs px-2 py-0.5 rounded bg-yellow-500/10 text-yellow-400 border border-yellow-500/20 font-mono">
              Live Queue
            </span>
          </h1>
          <p className="text-xs text-neutral-400">
            Triaged security detections generated by transparent rules and unsupervised ML anomaly engines
          </p>
        </div>
        <button
          onClick={fetchAlerts}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-neutral-900 border border-neutral-800 text-neutral-300 hover:text-yellow-400 hover:border-yellow-500/40 transition"
        >
          <RefreshCw className="w-3.5 h-3.5" />
          <span>Refresh Feed</span>
        </button>
      </div>

      {/* Status Tabs */}
      <div className="flex items-center justify-between border-b border-neutral-800/80 pb-2">
        <div className="flex gap-2">
          {['ALL', 'NEW', 'INVESTIGATING', 'RESOLVED', 'FALSE_POSITIVE'].map((tab) => (
            <button
              key={tab}
              onClick={() => {
                setStatusTab(tab);
                setPage(1);
              }}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-colors ${
                statusTab === tab
                  ? 'bg-yellow-500/15 text-yellow-400 border border-yellow-500/30'
                  : 'text-neutral-400 hover:text-neutral-200'
              }`}
            >
              {tab.replace('_', ' ')}
            </button>
          ))}
        </div>

        {/* Severity Selector */}
        <select
          value={severityFilter}
          onChange={(e) => {
            setSeverityFilter(e.target.value);
            setPage(1);
          }}
          className="bg-neutral-900 border border-neutral-800 rounded-lg px-2.5 py-1 text-xs text-neutral-300 focus:outline-none focus:border-yellow-500 transition"
        >
          <option value="">All Severities</option>
          <option value="CRITICAL">Critical</option>
          <option value="HIGH">High</option>
          <option value="MEDIUM">Medium</option>
          <option value="LOW">Low</option>
        </select>
      </div>

      {/* Alerts Table */}
      <div className="cyber-card overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead>
              <tr className="bg-slate-900/80 border-b border-slate-800 text-slate-400 font-semibold uppercase text-[10px]">
                <th className="py-2.5 px-4">Alert ID</th>
                <th className="py-2.5 px-3">Timestamp</th>
                <th className="py-2.5 px-3">Severity</th>
                <th className="py-2.5 px-3">Classification</th>
                <th className="py-2.5 px-3">Offending Source</th>
                <th className="py-2.5 px-3">Targeted Account</th>
                <th className="py-2.5 px-3">Risk Score</th>
                <th className="py-2.5 px-3">Lifecycle Status</th>
                <th className="py-2.5 px-4 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 font-mono text-[11px]">
              {loading ? (
                <tr>
                  <td colSpan="9" className="py-12 text-center text-neutral-500">
                    <RefreshCw className="w-5 h-5 text-yellow-400 animate-spin mx-auto mb-2" />
                    <span>Loading alerts repository...</span>
                  </td>
                </tr>
              ) : alerts.length > 0 ? (
                alerts.map((alt) => (
                  <tr
                    key={alt.id}
                    onClick={() => navigate(`/alerts/${alt.id}`)}
                    className="hover:bg-neutral-900/60 cursor-pointer transition-colors group"
                  >
                    <td className="py-3 px-4 font-bold text-yellow-400">
                      {alt.alert_id}
                    </td>
                    <td className="py-3 px-3 text-neutral-400 font-sans">
                      {new Date(alt.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' })}
                    </td>
                    <td className="py-3 px-3 font-sans">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-bold border ${severityBadges[alt.severity]}`}>
                        {alt.severity}
                      </span>
                    </td>
                    <td className="py-3 px-3 font-sans font-semibold text-neutral-200">
                      {alt.attack_type}
                    </td>
                    <td className="py-3 px-3 text-rose-400 font-mono">
                      {alt.source_ip || '-'}
                    </td>
                    <td className="py-3 px-3 font-sans text-neutral-300">
                      {alt.username || '-'}
                    </td>
                    <td className="py-3 px-3 font-bold text-amber-400 font-mono">
                      {alt.risk_score?.toFixed(0)} / 100
                    </td>
                    <td className="py-3 px-3 font-sans">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-semibold border ${statusBadges[alt.status]}`}>
                        {alt.status}
                      </span>
                    </td>
                    <td className="py-3 px-4 text-right">
                      <span className="text-yellow-400 group-hover:text-yellow-300 font-bold text-xs inline-flex items-center gap-1 font-sans">
                        Investigate <ArrowRight className="w-3.5 h-3.5" />
                      </span>
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan="9" className="py-12 text-center text-slate-500 font-sans">
                    No alerts in this category. Click "Run Security Simulation" to generate test alerts.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination */}
        <div className="flex items-center justify-between px-4 py-3 border-t border-slate-800 text-xs text-slate-400">
          <div>
            Total {total} alerts recorded
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={page <= 1}
              className="p-1 rounded bg-slate-900 border border-slate-800 disabled:opacity-30 hover:bg-slate-800"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <span className="font-mono text-slate-300">Page {page}</span>
            <button
              onClick={() => setPage((p) => p + 1)}
              disabled={alerts.length < 25}
              className="p-1 rounded bg-slate-900 border border-slate-800 disabled:opacity-30 hover:bg-slate-800"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
